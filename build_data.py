#!/usr/bin/env python3
"""Bundle ALL_relations.json for the static viewer. Python standard library only."""
import argparse
import json
from pathlib import Path

REQUIRED = ('subject', 'subject_type', 'relation', 'object', 'object_type')


def read_relations(path):
    with Path(path).open(encoding='utf-8-sig') as stream:
        data = json.load(stream)
    if not isinstance(data, list):
        raise ValueError('Expected a JSON array of relations')
    records = []
    for index, row in enumerate(data, 1):
        if not isinstance(row, dict):
            raise ValueError(f'Relation {index}: expected an object')
        missing = [key for key in REQUIRED if not isinstance(row.get(key), str) or not row[key].strip()]
        if missing:
            raise ValueError(f'Relation {index}: missing or empty fields: {", ".join(missing)}')
        cleaned = {key: value.strip() if isinstance(value, str) else value for key, value in row.items()}
        record = {key: value for key, value in cleaned.items() if key not in ('subject', 'relation', 'object')}
        record.update(subject_text=cleaned['subject'], predicate=cleaned['relation'], object_text=cleaned['object'])
        records.append(record)
    return records


def main():
    here = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, default=here / 'ALL_relations.json')
    parser.add_argument('--output', type=Path, default=here / 'data.js')
    args = parser.parse_args()
    try:
        records = read_relations(args.input)
    except (ValueError, OSError, json.JSONDecodeError) as error:
        parser.exit(1, f'Error: {error}\n')
    payload = json.dumps({'records': records}, ensure_ascii=True, separators=(',', ':'))
    args.output.write_text('// Generated by build_data.py; do not edit manually.\nwindow.KG_DATA = ' + payload + ';\n', encoding='utf-8')
    print(f'Bundled {len(records)} relations from {args.input} into {args.output}')


if __name__ == '__main__':
    main()
